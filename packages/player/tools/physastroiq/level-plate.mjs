// packages/player/tools/physastroiq/level-plate.mjs
//
// Общий каркас игровых карт уровней: холст, копилка структур и проверка
// расстановки областей. Сами карты лежат в levels-physics.mjs и
// levels-astro.mjs, рисует их draw-levels.mjs.
//
// ЗАЧЕМ КООРДИНАТЫ ОТДЕЛЬНЫМ ФАЙЛОМ. Вопрос привязан к прямоугольнику на
// картинке. Если координаты переписывать в банк вопросов руками, они
// разъедутся с рисунком при первой же правке — и это не сломает ни сборку, ни
// тесты: вопрос останется, картинка останется, а кликать надо будет в пустое
// место рядом с прибором. Ровно этот класс ошибки стоил Типу 7 примерно пятой
// части некликабельных вопросов. Здесь рисунок — единственный источник
// координат, а build-content.mjs берёт их по имени структуры; опечатка в
// имени падает на сборке.
//
// НА КАРТЕ УРОВНЯ НЕТ ПОДПИСЕЙ. Это игровое поле: подписанная структура — это
// ответ, написанный на картинке. Подписи есть у тематических изображений
// (draw-thematic.mjs) — то справочный материал, а не поле.
//
// ТОЧКИ БЕЗ ПРИВЯЗКИ К ВОПРОСУ (FR-013, строка 334: «не менее 10 координат
// точек без привязки») — это НЕ пустые места фона. Обманка ценна тем, что
// похожа на правильный ответ, поэтому под них нарисованы настоящие, но
// безымянные детали: клеммы схемы, звёзды поля, мелкие кратеры.
//
// ЧЕГО В ОБМАНКАХ БЫТЬ НЕ ДОЛЖНО — второго экземпляра того, что спрашивают.
// Два резистора на карте при вопросе «где резистор?» означают два правильных
// места и один засчитанный ответ. Поэтому каждая названная деталь на карте
// в своём роде единственная.

export const W = 1800;
export const H = 1200;

/**
 * Копилка одного уровня: рисунок собирается вперемешку со структурами, но
 * структура ВСЕГДА объявляется рядом с тем кодом, который её рисует.
 */
export function plate(bg) {
  const svg = [];
  const structures = [];
  const decoys = [];
  return {
    draw(...parts) {
      svg.push(...parts);
    },
    /** Структура: рисунок + кликабельная область + русское название для банка вопросов. */
    put(id, label, drawing, box) {
      svg.push(drawing);
      structures.push({ id, label, ...box });
    },
    /** Точка без привязки к вопросу: рисунок есть, имени нет. */
    decoy(drawing, box) {
      svg.push(drawing);
      decoys.push(box);
    },
    /**
     * Свободно ли место под область.
     *
     * Нужно там, где обманки расставляются циклом (звёзды фона, крепёж): их
     * координаты приходят из ГПСЧ или из списка, и попасть на уже размеченный
     * прибор они могут молча. checkPlacement такую накладку поймает, но
     * ценой падения сборки на каждой правке карты — а обманка тем и хороша,
     * что её ровно столько, сколько влезло.
     */
    fits(box) {
      return ![...structures, ...decoys].some(
        (r) => box.x < r.x + r.width && r.x < box.x + box.width && box.y < r.y + r.height && r.y < box.y + box.height
      );
    },
    build(title) {
      return {
        svg: `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <rect width="${W}" height="${H}" fill="${bg}"/>
  ${svg.join('\n  ')}
</svg>`,
        meta: { title, width: W, height: H, structures, decoys },
      };
    },
  };
}

function overlap(a, b) {
  return a.x < b.x + b.width && b.x < a.x + a.width && a.y < b.y + b.height && b.y < a.y + a.height;
}

/**
 * Налезающие друг на друга области — ошибка СБОРКИ, а не замечание.
 *
 * На игровом поле все области кликабельны одновременно, и две наложенные дают
 * кнопку поверх кнопки: клик достаётся верхней, а «правильный» ответ не
 * засчитывается. Ту же проверку делает model/completeness.ts над готовой
 * викториной, но там она сработает уже после сборки контента — а здесь падает
 * сразу, у того кода, который области и расставил.
 *
 * На первом прогоне карт «БиоIQ» эта проверка нашла восемь настоящих
 * наложений, включая область «Ядро», накрывшую «Ядрышко».
 */
export function checkPlacement(levelId, m) {
  const all = [
    ...m.structures.map((s) => ({ name: s.label, rect: s })),
    ...m.decoys.map((d, i) => ({ name: `точка без привязки №${i + 1}`, rect: d })),
  ];
  const bad = [];
  for (let i = 0; i < all.length; i += 1) {
    for (let j = i + 1; j < all.length; j += 1) {
      if (overlap(all[i].rect, all[j].rect)) bad.push(`${all[i].name} ↔ ${all[j].name}`);
    }
  }
  const outside = all.filter(
    (a) => a.rect.x < 0 || a.rect.y < 0 || a.rect.x + a.rect.width > W || a.rect.y + a.rect.height > H
  );
  const duplicateIds = [];
  const seen = new Set();
  for (const s of m.structures) {
    if (seen.has(s.id)) duplicateIds.push(s.id);
    seen.add(s.id);
  }
  // Требование FR-013 (строка 334) называет число: не меньше десяти точек без
  // привязки. Проверяем здесь же, у того кода, который их расставил.
  const tooFewDecoys = m.decoys.length < 10;

  if (bad.length || outside.length || duplicateIds.length || tooFewDecoys) {
    console.error(`\nуровень ${levelId} «${m.title}»: области расставлены неверно`);
    for (const b of bad) console.error('  налезают: ' + b);
    for (const o of outside) console.error('  за краем картинки: ' + o.name);
    for (const d of duplicateIds) console.error('  повторный идентификатор структуры: ' + d);
    if (tooFewDecoys) console.error(`  точек без привязки ${m.decoys.length}, требуется не меньше 10 (FR-013)`);
    return false;
  }
  return true;
}
