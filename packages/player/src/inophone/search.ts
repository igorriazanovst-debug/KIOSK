// Правило поиска по словарю (ТЗ строка 90).
//
// Вынесено из экрана отдельным файлом не ради чистоты, а чтобы его можно было
// ПРОВЕРИТЬ ТЕСТОМ. «Ковер находит ковёр» — утверждение о поведении продукта,
// а не деталь вёрстки, и жить оно должно там, где за ним следят.

import type { inophone } from '@kiosk/shared';

/**
 * Приведение строки к виду, в котором сравнение осмысленно.
 *
 * РЕГИСТР И «Ё» НЕ РЕШАЮТ СУДЬБУ ПОИСКА. На клавиатуре у доски «ё» набирают
 * единицы, и пустая выдача по запросу «ковер» читается как «такого слова в
 * программе нет» — то есть как дефект контента, которого нет.
 */
export function fold(value: string): string {
  return value.toLowerCase().replace(/ё/g, 'е').trim();
}

/**
 * Подходит ли понятие под запрос.
 *
 * Ищем ПО ВСЕМ ЯЗЫКАМ СРАЗУ, а не по выбранному. Пособие открывает человек,
 * который ищет слово тем языком, каким владеет; требовать, чтобы он сначала
 * указал язык поиска, — значит задавать вопрос, которого он себе не задавал.
 */
export function matches(concept: inophone.Concept, query: string): boolean {
  const q = fold(query);
  if (q === '') return true;
  return Object.values(concept.translations).some((t) => t && fold(t.text).includes(q));
}
