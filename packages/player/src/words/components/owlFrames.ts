// packages/player/src/words/components/owlFrames.ts
// Покадровая анимация совы-помощника: какой кадр показывать в момент времени.
//
// Вынесено из компонента отдельным чистым модулем намеренно. Отрисовку
// проверить автотестом в этом пакете нечем (среды для тестов React-компонентов
// нет), а вот «через сколько сова моргнёт» и «чередуются ли кадры речи» —
// обычная арифметика, и она покрывается юнит-тестами. Тот же принцип, что и во
// всём проекте: домен тестами, интерфейс живым прогоном.
//
// Функция ЧИСТАЯ и зависит только от прошедшего времени: компонент дёргает её
// на каждом кадре анимации, а не хранит состояние сам. Побочный выигрыш —
// анимация не рассыпается при перемонтировании и не требует очистки таймеров
// с состоянием.

/** Настроение задаётся снаружи — по ходу игры */
export type OwlMood = 'idle' | 'speaking' | 'pointing' | 'happy';

/** Кадр — это имя файла в public/words-owl/owl-<кадр>.webp */
export type OwlFrame = 'idle' | 'blink' | 'speaking' | 'pointing' | 'happy';

/** Раз в столько сова моргает в покое */
export const BLINK_PERIOD_MS = 4200;
/** Сколько длится моргание */
export const BLINK_DURATION_MS = 160;
/** Как часто сменяются кадры речи: примерно темп слогов */
export const SPEECH_FRAME_MS = 180;

/**
 * Кадр для настроения в заданный момент.
 *
 * @param mood настроение, заданное экраном
 * @param elapsedMs сколько прошло с начала анимации этого настроения
 */
export function owlFrame(mood: OwlMood, elapsedMs: number): OwlFrame {
  const t = Math.max(0, elapsedMs);

  switch (mood) {
    case 'speaking':
      // Клюв открывается и закрывается — иллюзия речи. Чередуются именно
      // «говорит» и «покой», а не два разных кадра речи: так рисунков нужно
      // меньше, а разница на глаз та же.
      return Math.floor(t / SPEECH_FRAME_MS) % 2 === 0 ? 'speaking' : 'idle';

    case 'pointing':
      // Указание — жест, а не цикл: он должен читаться однозначно, поэтому
      // кадр не меняется. Лёгкое покачивание добавляет компонент средствами CSS.
      return 'pointing';

    case 'happy':
      return 'happy';

    case 'idle':
    default: {
      // Моргание в конце периода: большую часть времени глаза открыты
      const phase = t % BLINK_PERIOD_MS;
      return phase >= BLINK_PERIOD_MS - BLINK_DURATION_MS ? 'blink' : 'idle';
    }
  }
}

/**
 * Нужна ли покадровая перерисовка для этого настроения. Статичные жесты
 * незачем гонять через requestAnimationFrame — на слабом железе киоска это
 * заметно, а пользы ноль.
 */
export function isAnimated(mood: OwlMood): boolean {
  return mood === 'idle' || mood === 'speaking';
}
