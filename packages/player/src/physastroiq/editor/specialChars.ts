// FR-015 ТЗ 11 (строка 336) — набор спецсимволов для текста вопроса, ответа и
// подсказки.
//
// ОТДЕЛЬНО ОТ SpecialCharPicker.tsx, чтобы набор можно было проверить тестом:
// прогон тестов плеера идёт через `node --experimental-strip-types`, а он
// понимает .ts и не понимает .tsx. Состав набора — содержательное решение,
// которое легко потерять обратным копированием от «БиоIQ», не заметив, —
// значит, он должен быть под тестом.
//
// НАБОР СОБРАН ПОД ФИЗИКУ И АСТРОНОМИЮ (FR-004, строка 325: предмет —
// физика, астрономия), а не скопирован от биологии как есть.
//
// Что ОСТАВЛЕНО от прежнего набора, и это не недосмотр:
//   ₀–₉  — индексы величин: v₀ (начальная скорость), t₁ и t₂, F₁ и F₂,
//          R₁ при последовательном соединении. Без них задачу не набрать;
//   ⁰–⁹  — степени: 3·10⁸ м/с, 9,8 м/с², постоянная Планка;
//   ⁺ ⁻  — знак степени (10⁻¹⁹ Кл) и знак заряда (ион, электрод);
//   →    — вектор и направление процесса;
//   ↔    — обратимый процесс, двусторонний переход;
//   × ± ≈ ° μ — умножение в записи 3×10⁸, погрешность измерения,
//          градус (и угол, и температура), приставка «микро».
//
// Что ДОБАВЛЕНО именно для физики:
//   ·    — знак умножения В ЕДИНИЦАХ: Н·м, кг·м/с, Вт·ч. Ставить здесь × —
//          распространённая ошибка записи, и панель не должна её подсказывать;
//   √    — формула математического маятника T = 2π√(l/g);
//   Δ    — изменение величины: Δt, Δv, ΔU. Школьная запись всюду;
//   π    — длина окружности, период колебаний, угловая мера;
//   λ    — длина волны, ν для частоты НЕ добавлена намеренно (см. ниже);
//   ω    — угловая скорость, циклическая частота;
//   Ω    — ом, единица сопротивления;
//   α β γ — три вида радиоактивного излучения и углы падения/преломления.
//
// Что ДОБАВЛЕНО именно для астрономии:
//   ☉    — Солнце: масса M☉ и светимость L☉, мера сравнения звёзд;
//   ☾    — Луна;
//   ⊕    — Земля: массы и радиусы планет школьник сравнивает как M⊕ и R⊕;
//   ′ ″  — угловые минуты и секунды: координаты на карте звёздного неба и
//          видимый угловой размер (диск Луны — около 31′).
//
// Что НЕ добавлено и почему:
//   ν (ню) — начертание неотличимо от латинской v, а рядом с ней в одной
//          формуле (v — скорость, ν — частота) это источник неверного ответа.
//          Частоту школьник записывает буквой f, её на панели искать не нужно;
//   остальной греческий алфавит — ξ, ψ, ζ, η, θ и прочие в школьном курсе
//          не встречаются, а панель на семьдесят кнопок перестаёт быть
//          быстрее клавиатуры.

const GENERAL_CHARS = ['«', '»', '—', '–', '…', '№', '§', 'ё', 'Ё', '©'];
const SUBSCRIPT_DIGITS = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇', '₈', '₉'];
const SUPERSCRIPT_DIGITS = ['⁰', '¹', '²', '³', '⁴', '⁵', '⁶', '⁷', '⁸', '⁹'];
const SIGN_MARKS = ['⁺', '⁻'];
const ARROWS = ['→', '↔'];
const PHYSICS_CHARS = ['°', '±', '×', '·', '≈', '√', 'Δ', 'λ', 'ω', 'Ω', 'π', 'α', 'β', 'γ', 'μ'];
const ASTRONOMY_CHARS = ['☉', '☾', '⊕', '′', '″'];

export const PHYSASTROIQ_SPECIAL_CHARS: readonly string[] = [
  ...GENERAL_CHARS,
  ...SUBSCRIPT_DIGITS,
  ...SUPERSCRIPT_DIGITS,
  ...SIGN_MARKS,
  ...ARROWS,
  ...PHYSICS_CHARS,
  ...ASTRONOMY_CHARS,
];
