// packages/player/src/bioiq/editor/specialChars.ts
// FR-015 ТЗ 10 (строка 309) — набор спецсимволов для текста вопроса, ответа и
// подсказки.
//
// ОТДЕЛЬНО ОТ SpecialCharPicker.tsx, чтобы набор можно было проверить тестом:
// прогон тестов плеера идёт через `node --experimental-strip-types`, а он
// понимает .ts и не понимает .tsx. Состав набора — содержательное решение,
// которое легко потерять обратным копированием от «ХимIQ», не заметив, —
// значит, он должен быть под тестом.
//
// НАБОР СОБРАН ПОД БИОЛОГИЮ, а не скопирован от химии как есть.
//
// Что ОСТАВЛЕНО из химического набора, и это не недосмотр: подстрочные и
// надстрочные цифры биологии нужны не меньше. Фотосинтез записывается как
// 6CO₂ + 6H₂O → C₆H₁₂O₆ + 6O₂, дыхание — обратной формулой, и без индексов
// вопрос про них набрать нечем. Заряды (Na⁺, K⁺, Ca²⁺) — мембранный транспорт
// и потенциал действия. Стрелка → нужна и реакции, и цепи питания
// (трава → заяц → лиса).
//
// Что ДОБАВЛЕНО именно для биологии:
//   ♀ ♂  — пол в задачах на наследование, признак, сцепленный с полом;
//   ×     — скрещивание (АА × аа), знак гибридизации;
//   °     — температура (тело 36,6 °C, денатурация белка);
//   μ     — микрометр: размеры клеток и органелл измеряются в мкм;
//   ‰     — промилле: солёность среды;
//   ±     — разброс измерения в опыте;
//   ≈     — приблизительное значение;
//   ↔     — обратимый процесс, двусторонняя связь в схеме;
//   α β   — α-спираль и β-лист белка, α- и β-клетки поджелудочной железы.
//
// Что НЕ добавлено: греческий алфавит целиком. Нужны из него ровно две буквы,
// а полный набор превратил бы панель в двадцать четыре кнопки, среди которых
// эти две пришлось бы искать.

const GENERAL_CHARS = ['«', '»', '—', '–', '…', '№', '§', 'ё', 'Ё', '©'];
const SUBSCRIPT_DIGITS = ['₀', '₁', '₂', '₃', '₄', '₅', '₆', '₇', '₈', '₉'];
const SUPERSCRIPT_DIGITS = ['⁰', '¹', '²', '³', '⁴', '⁵', '⁶', '⁷', '⁸', '⁹'];
const CHARGE_SIGNS = ['⁺', '⁻'];
const ARROWS = ['→', '↔'];
const BIOLOGY_CHARS = ['♀', '♂', '×', '°', 'μ', '‰', '±', '≈', 'α', 'β'];

export const BIOIQ_SPECIAL_CHARS: readonly string[] = [
  ...GENERAL_CHARS,
  ...SUBSCRIPT_DIGITS,
  ...SUPERSCRIPT_DIGITS,
  ...CHARGE_SIGNS,
  ...ARROWS,
  ...BIOLOGY_CHARS,
];
