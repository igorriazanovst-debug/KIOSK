// Закрытие FR-008/FR-015 ТЗ (строки 247, 254 — «изображение к КАЖДОМУ
// вопросу») по решению пользователя 2026-09-16, после разбора конкретных
// примеров: персональная иллюстрация под каждый из 168 вопросов в
// подавляющем большинстве случаев спойлерит ответ буквально (вопрос
// «какова формула воды» + картинка молекулы с подписями O/H — это
// готовый ответ, не иллюстрация) или сильно на него намекает (вопрос
// «в какой посуде удобно нагревать» + картинка именно колбы). Это не
// решается более аккуратным рисунком — структурное свойство вопросов
// «как это называется», которых в банке большинство.
//
// Решение: НЕЙТРАЛЬНАЯ картинка по ТЕМЕ вопроса (общая на всех ~28
// вопросов темы), не привязанная к конкретному ответу — тот же принцип,
// что уже применяется к картинке-карте уровня (общая на много вопросов),
// только для второго слота (иллюстрация НАД текстом вопроса). Каждый
// вопрос при показе на игровом поле получает изображение (буква
// требования выполнена), но оно не выдаёт ответ.
//
// НЕ используется schema-поле question.questionImage + chimiqItemImageUrl
// (chimiqmedia://item/...) - тот протокол резолвит путь против
// %AppData%/kiosk-chimiq/quizzes (папка ЗАГРУЖЕННЫХ через редактор
// картинок пользовательской викторины), а не против public/, где лежат
// бандловые ассеты встроенной викторины - 404 для builtin quiz. Плоский
// относительный путь в public/ (тот же приём, что levelImageUrl) работает
// для builtin-контента напрямую.

const THEME_IMAGE_FILE: Record<string, string> = {
  'Экспериментальная химия': 'experimental.png',
  'Химические элементы': 'elements.png',
  'Строение атома': 'atom.png',
  'Химические соединения': 'compounds.png',
  'История химии': 'history.png',
  'Таблица Менделеева': 'periodic.png',
};

export const CHIMIQ_QUESTION_THEMES: string[] = Object.keys(THEME_IMAGE_FILE);

export function questionThemeImageUrl(theme: string): string | null {
  const fileName = THEME_IMAGE_FILE[theme];
  return fileName ? `./chimiq/questionThemes/${fileName}` : null;
}
