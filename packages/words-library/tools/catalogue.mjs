/**
 * Уровень слова по его месту в теме. Не «трудность слова», а механика показа:
 * первые слова темы даются с силуэтом, дальше без него.
 *
 * Распределение внутри темы, а не по всему словарю: педагог выбирает уровень
 * ТЕМЕ, и в каждой теме должны быть слова всех трёх уровней, иначе выбор
 * уровня в настройках ничего бы не менял.
 */
export function levelOf(indexInTheme) {
  if (indexInTheme < 6) return 0;
  if (indexInTheme < 12) return 1;
  return 2;
}

/** Идентификатор слова: номер темы × 100 + номер внутри темы, четыре цифры */
export function wordId(themeIndex, indexInTheme) {
  return String(themeIndex * 100 + indexInTheme).padStart(4, '0');
}

/** Библиотека в том виде, в каком её ждёт схема пакета */
export function buildLibrary() {
  const words = [];
  const themes = THEMES.map((theme, themeIndex) => {
    const wordIds = theme.words.map((name, i) => {
      const id = wordId(themeIndex, i);
      words.push({ id, name, themeId: theme.id, level: levelOf(i) });
      return id;
    });
    return { id: theme.id, title: theme.title, intro: theme.intro, wordIds };
  });
  return { themes, words };
}
