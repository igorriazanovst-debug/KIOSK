// Шесть языков виджета «Инофон» (Тип 4).
//
// ТЗ называет их дважды: строка 87 — язык интерфейса, строка 88 — изучаемые
// языки. Список один и тот же, поэтому и в коде он один: два списка «те же
// шесть языков» неизбежно разъедутся, а разъехавшись, дадут язык, на котором
// можно учиться, но нельзя читать интерфейс.
//
// НАЗВАНИЕ ЯЗЫКА — НА НЁМ САМОМ. Ребёнок и педагог ищут в списке «Deutsche», а
// не «немецкий»: так устроены все многоязычные программы, и так же сделано у
// эталона. Русское название хранится отдельно — оно нужно там, где интерфейс
// заведомо русский (приёмочные документы, отчёты проверки комплектности).
//
// ЯЗЫКОВ РОВНО ШЕСТЬ. У эталона в данных лежит ещё и полный испанский — 391
// слово с текстом и звуком, — но в списке выбора его нет: около девяти
// мегабайт поставки, недоступных пользователю. Повторять это не будем.

/** Код языка. Совпадает с ISO 639-1, кроме башкирского — там 639-2/T. */
export const LANGUAGE_CODES = ['ru', 'en', 'fr', 'de', 'zh', 'ba'] as const;
export type LanguageCode = (typeof LANGUAGE_CODES)[number];

export interface LanguageInfo {
  code: LanguageCode;
  /** Как язык называет себя сам — именно это видит пользователь в списке */
  nativeName: string;
  /** Русское название — для документов приёмки и отчётов сборки */
  russianName: string;
  /**
   * Тег культуры для синтеза речи. Нужен ИНСТРУМЕНТАМ СБОРКИ озвучки: они
   * спрашивают у системы голос по этому тегу. Для башкирского общего тега
   * нет — ba-RU не признаёт ни один известный синтезатор, и это записано
   * честно, а не подогнано под несуществующий голос.
   *
   * ЭТО НЕ ОТВЕТ НА ВОПРОС «ЕСТЬ ЛИ ПРОИЗНОШЕНИЕ В ПАКЕТЕ». Башкирский
   * озвучен моделью Silero, 444 записи лежат в пакете, а системного тега у
   * него по-прежнему нет. Интерфейс, выводивший «озвучка недоступна» отсюда,
   * сообщал педагогу неправду о том, что лежит рядом на диске. Наличие
   * записей спрашивается у пакета (translations[code].hasAudio), а не здесь.
   */
  speechTag: string | null;
}

export const LANGUAGES: readonly LanguageInfo[] = [
  { code: 'ru', nativeName: 'Русский', russianName: 'русский', speechTag: 'ru-RU' },
  { code: 'en', nativeName: 'English', russianName: 'английский', speechTag: 'en-US' },
  { code: 'fr', nativeName: 'Français', russianName: 'французский', speechTag: 'fr-FR' },
  { code: 'de', nativeName: 'Deutsch', russianName: 'немецкий', speechTag: 'de-DE' },
  { code: 'zh', nativeName: '中文', russianName: 'китайский', speechTag: 'zh-CN' },
  { code: 'ba', nativeName: 'Башҡорт', russianName: 'башкирский', speechTag: null },
];

const BY_CODE = new Map(LANGUAGES.map((l) => [l.code, l]));

export function languageInfo(code: LanguageCode): LanguageInfo {
  const info = BY_CODE.get(code);
  // Код приходит из настроек на диске, а они правятся руками и переживают
  // обновления. Молча подставить русский нельзя: пользователь увидит не тот
  // язык и решит, что программа его не понимает
  if (!info) throw new Error(`неизвестный код языка: ${String(code)}`);
  return info;
}

export function isLanguageCode(value: unknown): value is LanguageCode {
  return typeof value === 'string' && BY_CODE.has(value as LanguageCode);
}

/**
 * Сколько изучаемых языков можно выбрать одновременно.
 *
 * У эталона предел — три, и он зашит циклом `for (let i = 0; i < 3; i++)` в
 * карточке объекта. ТЗ строка 88 говорит «одного, нескольких» и верхней
 * границы не ставит, так что три требованию не противоречат.
 *
 * Здесь предел тоже три, но по другой причине и осознанно: карточка объекта
 * проигрывает произношение ПОДРЯД — родной язык, затем изучаемые. Шесть
 * языков подряд это около двенадцати секунд ожидания на каждом щелчке, и
 * ребёнок перестанет дожидаться конца. Предел живёт здесь одной константой, а
 * не в цикле вёрстки, чтобы его можно было изменить в одном месте.
 */
export const MAX_STUDY_LANGUAGES = 3;

/** Язык интерфейса и родной язык по умолчанию */
export const DEFAULT_INTERFACE_LANGUAGE: LanguageCode = 'ru';

/** Что предлагается изучать при первом запуске */
export const DEFAULT_STUDY_LANGUAGES: readonly LanguageCode[] = ['en'];
