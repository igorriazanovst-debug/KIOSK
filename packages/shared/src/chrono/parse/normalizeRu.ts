// Минимальная нормализация ввода перед прогоном через правила: обрезка
// пробелов, нижний регистр, схлопывание повторных пробелов, приведение
// тире/en-dash/em-dash к одному дефису (нужно и для интервалов через тире —
// "1900 - 2000", — и потому что пользователи не различают их на клавиатуре).
// Суффиксы вида "год"/"года"/"г." каждое правило разбирает само через
// альтернацию в своём регулярном выражении — не здесь, чтобы не собирать
// в одном месте знание обо всех формах сразу.

export function normalizeRu(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/[–—]/g, '-')
    .replace(/\s+/g, ' ');
}
