// packages/shared/src/utils/seats.ts
// Места вокруг интерактивного стола и поворот интерфейса для каждого.
//
// ОБЩЕЕ НА ТРИ ВИДЖЕТА. Правило одно и то же у «Я знаю много слов» (ТЗ
// строка 54), «АзбукоСлов» (строка 75) и «Инофона» (строка 89): до четырёх
// человек вокруг стола, интерфейс поворачивается к тому, чей ход. Копий
// сначала было две, и третья превратила бы расхождение в вопрос времени —
// такое расхождение не падает, оно просто делает один виджет хуже другого, и
// замечают это на занятии.
//
// ЗНАЧЕНИЯ СНЯТЫ С ЭТАЛОНА ЖИВЫМ ПРОГОНОМ, вычисленными стилями, а не
// выведены из соображений симметрии: снизу 0°, слева 90°, сверху 180°,
// справа −90°.

export const SEAT_ROTATIONS = [0, 90, 180, -90] as const;

/** Подпись места для экрана рассадки */
export const SEAT_LABELS = ['снизу', 'слева', 'сверху', 'справа'] as const;

/**
 * Какие места занимаются при данном числе игроков.
 *
 * Правило снято с эталона: при двоих — противоположные стороны (друг напротив
 * друга, а не рядом), при троих третий садится сверху. Это не эстетика: двое,
 * усаженные рядом, закрывают друг другу половину доски.
 */
export function seatsFor(playerCount: number): number[] {
  switch (playerCount) {
    case 1:
      return [0];
    case 2:
      return [0, 2];
    case 3:
      return [0, 1, 2];
    default:
      return [0, 1, 2, 3];
  }
}

/** Угол поворота интерфейса для игрока, чей ход сейчас */
export function seatRotationFor(playerIndex: number, playerCount: number): number {
  const seats = seatsFor(playerCount);
  return SEAT_ROTATIONS[seats[playerIndex % seats.length]];
}
