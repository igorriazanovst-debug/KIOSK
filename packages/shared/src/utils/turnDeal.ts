// packages/shared/src/utils/turnDeal.ts
// Раздача загаданных заданий по ходам партии.
//
// ЗАЧЕМ ОБЩИЙ МОДУЛЬ. «Я знаю много слов» (Тип 2) и «АзбукоСлов» (Тип 3)
// строят партию по-разному — там шаг с вариантами-картинками, здесь вопрос
// одного из трёх этапов, — но правило раздачи у них обязано быть одним и тем
// же: дети играют за одним столом и видят задания друг друга. Два движка с
// собственными копиями подобного алгоритма разошлись бы на первой же правке,
// и разойтись они могли бы молча: раздача не падает, она просто становится
// хуже. Поэтому правило живёт в одном месте и проверяется одним набором
// тестов.
//
// ЧТО ИМЕННО ГАРАНТИРУЕТСЯ:
//
// 1. В пределах одного круга задания игроков не повторяются — когда заданий
//    в запасе не меньше, чем игроков. Круг это подряд идущие ходы всех
//    игроков, то есть ровно то, что дети видят одновременно: «а почему у него
//    такое же слово, как у меня». Это и есть главное требование.
// 2. Одному игроку одно задание не выпадает двумя его ходами подряд — когда
//    заданий в запасе СТРОГО больше, чем игроков. Это не то же самое, что
//    пункт 1: ходы одного игрока отстоят друг от друга ровно на число
//    игроков, и правило, разводящее только соседей по кругу, такой повтор
//    пропускает.
// 3. Для игры в одиночку оба правила вырождаются в прежнее: одно и то же
//    задание не встаёт двумя ходами подряд.
// 4. Запас расходуется равномерно: раздача идёт полными перемешанными
//    проходами, поэтому за партию каждое задание использовано одинаковое
//    число раз с точностью до единицы. Ни одно не «любимое».
//
// ГРАНИЦА ПУНКТА 2, найденная тестом. Когда заданий ровно столько же, сколько
// игроков, оба правила вместе невыполнимы для этой раздачи: чтобы круг был
// чист, каждый круг обязан быть перестановкой ВСЕГО запаса, а тогда выбор
// первого задания следующего круга сводится к единственному не занятому в
// хвосте предыдущего — и оно достаётся тому же игроку. Развести это можно
// только раздачей кругами-перестановками со смещением, а не пошаговым
// выбором; ради случая «педагог собрал комплект ровно из четырёх слов на
// четверых» такая сложность не окупается. В этом случае держится пункт 1,
// пункт 2 может нарушиться. Если запас меньше числа игроков, не держится и
// пункт 1: четырём игрокам не раздать три разных слова.
//
// ЧЕГО НЕ ГАРАНТИРУЕТСЯ — и это стоит знать, потому что звучит похоже.
// Неверно, будто задание повторяется только после того, как исчерпан весь
// запас. Последовательность склеена из перестановок запаса, и на стыке двух
// проходов задание с конца одного законно оказывается недалеко от себя же в
// начале следующего. Гарантируется не расстояние вообще, а именно окно из
// пунктов 1 и 2. Первая редакция этого модуля утверждала обратное, и поймал
// это тест, а не вычитка.
//
// ЧЕГО ГАРАНТИРОВАТЬ НЕЛЬЗЯ. Если заданий в запасе меньше, чем игроков,
// развести их физически невозможно — четырём игрокам не раздать три разных
// слова. В этом случае раздача не падает и не зацикливается, а делает лучшее
// из возможного: занятие важнее формальной чистоты, а педагог, собравший
// комплект из трёх слов на четверых, увидит повтор и сам поймёт причину.

export type TurnDealRng = () => number;

export interface TurnDealOptions {
  /** Всего ходов в партии: игроков × заданий на игрока */
  turns: number;
  /** Сколько игроков за столом — из этого выводится ширина круга */
  players: number;
  rng: TurnDealRng;
}

function shuffle<T>(items: readonly T[], rng: TurnDealRng): T[] {
  const copy = items.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export class TurnDealError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'TurnDealError';
  }
}

/**
 * Загаданные задания на все ходы партии, В ПОРЯДКЕ ХОДА.
 *
 * Порядок хода, а не «по игрокам» — принципиально. Раздача по игрокам (каждому
 * свой независимый список) и была прежним поведением обоих виджетов: каждый
 * список сам по себе выглядел прилично, а за столом дети регулярно получали
 * одно и то же слово одновременно. Свойство, которое требуется, — свойство
 * ПОСЛЕДОВАТЕЛЬНОСТИ ХОДОВ, поэтому и строится она целиком.
 *
 * Разложить обратно по игрокам умеет вызывающий: ход t принадлежит игроку
 * `t % players`, и это его `Math.floor(t / players)`-й вопрос.
 */
export function dealTurnTargets<T>(
  pool: readonly T[],
  options: TurnDealOptions
): T[] {
  const { turns, players, rng } = options;
  if (pool.length === 0) throw new TurnDealError('раздавать нечего: запас заданий пуст');
  if (players < 1) throw new TurnDealError('в партии нужен хотя бы один игрок');
  if (turns < 1) throw new TurnDealError('в партии нужен хотя бы один ход');

  // Сколько предыдущих ходов не должны повториться.
  //
  // Ровно число игроков, а не «на единицу меньше». Развести ход с N-1
  // предыдущими хватило бы, чтобы круг из N игроков был чист, — но ходы
  // ОДНОГО игрока отстоят друг от друга ровно на N, и такое правило пропускало
  // бы повтор у одного и того же ребёнка двумя его ходами подряд. Для
  // одиночной игры N = 1, и правило совпадает с прежним «не два раза подряд».
  //
  // Верхняя граница — pool.length - 1: требовать больше, чем есть заданий,
  // значит требовать невозможного.
  const lookBack = Math.min(players, pool.length - 1);

  const dealt: T[] = [];
  while (dealt.length < turns) {
    const pass = shuffle(pool, rng);
    for (let i = 0; i < pass.length && dealt.length < turns; i++) {
      if (lookBack > 0) {
        const recent = dealt.slice(-lookBack);
        if (recent.includes(pass[i])) {
          // Конфликт бывает только на стыке проходов: внутри прохода повторов
          // нет по построению. Чиним обменом с ближайшим неконфликтующим
          // заданием ЭТОГО ЖЕ прохода — перемешивать проход заново нельзя,
          // это могло бы не сойтись и зациклиться, а обмен всегда конечен и
          // сохраняет главное свойство: проход остаётся полным перебором
          // запаса, значит правило «повтор только после исчерпания» цело.
          const swapWith = pass.findIndex(
            (candidate, k) => k > i && !recent.includes(candidate)
          );
          if (swapWith !== -1) {
            [pass[i], pass[swapWith]] = [pass[swapWith], pass[i]];
          }
          // Не нашли — значит заданий меньше, чем игроков. Отдаём как есть
        }
      }
      dealt.push(pass[i]);
    }
  }

  return dealt;
}

/**
 * Ход `turn` принадлежит этому игроку. Вынесено рядом с раздачей, чтобы оба
 * виджета раскладывали ходы по игрокам одинаково и совпадали с собственным
 * порядком хода в партии: игроки ходят по кругу, круг замыкается — номер
 * задания растёт.
 */
export function playerIndexForTurn(turn: number, players: number): number {
  return turn % players;
}
