// Авторский словарь пакета «АзбукоСлов»: буква → слова → слоги.
//
// СЛОВАРЬ НАПИСАН ЗДЕСЬ, А НЕ ВЗЯТ У ЭТАЛОНА. ТЗ раздел 10 требует
// обеспечить законность использования всех материалов, и разбор Тип 2 прямо
// записал: ресурсы ОС3 использовать нельзя ни в каком виде. Сами слова —
// обиходные русские существительные, и совпадения с чужим списком
// неизбежны и безобидны; заимствован не список, а только УСТРОЙСТВО
// каталога, которое и не может быть иным.
//
// ТРИ БУКВЫ — ОСОБЫЕ. Ъ, Ы и Ь не могут начать слово, поэтому у них
// перечисляются слова, где буква стоит ВНУТРИ. Ровно так же поступает
// эталон, и иначе нельзя: требование ТЗ строки 71 («не менее 2 картинок на
// каждую букву») для этих трёх было бы невыполнимо в принципе.
//
// Отсюда следствие: одно слово законно стоит у двух букв — «Рыба» у Р и у Ы,
// «Медведь» у М и у Ь. Проверка графа это допускает.
//
// РАЗБИВКА НА СЛОГИ — по числу гласных, с открытым слогом там, где он
// возможен. Именно она, а не написание, определяет этапы 2 и 3, поэтому
// пишется руками и проверяется глазами, а не выводится алгоритмом: русское
// слогоделение имеет исключения, а ошибка здесь звучит на занятии.

/** Алфавит: индекс в строке + 1 = номер буквы, он же имя файла озвучки */
export const ALPHABET = 'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ';

/**
 * Транслитерация в идентификатор. Правила эталона (`avtobus`, `apel_sin`,
 * `mysh_`) с одним дополнением: Э даёт «eh», а не «e».
 *
 * Без этого «э» из «э-лек-трич-ка» и «е» из «е-нот» дают ОДИН идентификатор
 * слога, а значит один файл `media/e.mp3` на два разных звука — то самое
 * молчаливое перезаписывание, которое ловит checkPathCollisions. Дешевле
 * развести их в транслитерации, чем ловить потом на занятии.
 */
const TRANSLIT = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh', з: 'z',
  и: 'i', й: 'j', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '_', ы: 'y', ь: '_', э: 'eh', ю: 'yu', я: 'ya',
};

export function translit(text) {
  return [...text.toLowerCase()]
    .map((ch) => {
      const mapped = TRANSLIT[ch];
      if (mapped === undefined) throw new Error(`нечем транслитерировать «${ch}» в «${text}»`);
      return mapped;
    })
    .join('');
}

/** Номер буквы в алфавите, 1..33 */
export function letterNumber(ch) {
  const index = ALPHABET.indexOf(ch.toUpperCase());
  if (index < 0) throw new Error(`«${ch}» не буква русского алфавита`);
  return index + 1;
}

