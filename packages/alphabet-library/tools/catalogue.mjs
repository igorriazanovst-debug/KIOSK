/** Разбирает строку «ав-то-бус» в слово каталога */
export function parseEntry(spelled, letter) {
  const syllables = spelled.split('-').filter(Boolean);
  if (syllables.length === 0) throw new Error(`пустая запись у буквы ${letter}`);
  const name = syllables.join('');
  return {
    id: translit(name),
    // Слово показывается ребёнку с заглавной буквы, как в азбуке
    name: name.charAt(0).toUpperCase() + name.slice(1),
    syllables,
  };
}

/** Полный разбор каталога в плоские списки слов и слогов */
export function buildCatalogue() {
  const words = new Map();
  const syllables = new Map();
  const lettersWords = new Map();

  for (const [letter, entries] of Object.entries(CATALOGUE)) {
    const number = letterNumber(letter);
    const ids = [];
    for (const spelled of entries) {
      const entry = parseEntry(spelled, letter);

      const syllableIds = entry.syllables.map((syllableName) => {
        const id = translit(syllableName);
        const existing = syllables.get(id);
        if (existing && existing.name !== syllableName) {
          // Два разных слога с одним идентификатором — это один файл на два
          // звука. Ловим на сборке, а не на занятии
          throw new Error(
            `слоги «${existing.name}» и «${syllableName}» дают один идентификатор «${id}»`
          );
        }
        if (!existing) {
          syllables.set(id, {
            id,
            name: syllableName,
            letterNumbers: [...syllableName].map(letterNumber),
          });
        }
        return id;
      });

      const existingWord = words.get(entry.id);
      if (existingWord) {
        if (existingWord.name !== entry.name) {
          throw new Error(`слова «${existingWord.name}» и «${entry.name}» дают один идентификатор`);
        }
      } else {
        words.set(entry.id, {
          id: entry.id,
          name: entry.name,
          syllableIds,
          // Запись «без последнего слога» имеет смысл только у многосложных
          hasWithoutLastSyllable: syllableIds.length >= 2,
        });
      }
      ids.push(entry.id);
    }
    lettersWords.set(number, ids);
  }

  // Слово ОБЯЗАНО стоять у своей первой буквы, даже если в таблице выше оно
  // записано только у другой. Строки Ъ, Ы и Ь как раз такие: «Подъезд» там
  // записан у Ъ, потому что иллюстрирует именно Ъ, — но первая его буква П,
  // и без записи у П этап «покажи букву» никогда не предложит это слово,
  // хотя в пакете оно есть. Эталон поступает так же: Подъезд стоит и у П,
  // и у Ъ.
  //
  // Шаг явный, а не в таблице руками: забыть его при добавлении слова легко,
  // и проверка графа тогда падает на сборке — что и случилось в первый раз.
  for (const word of words.values()) {
    const firstSyllable = syllables.get(word.syllableIds[0]);
    const first = firstSyllable?.letterNumbers[0];
    if (first === undefined) continue;
    const list = lettersWords.get(first);
    if (list && !list.includes(word.id)) list.push(word.id);
  }

  const letters = [...ALPHABET].map((name, index) => ({
    number: index + 1,
    name,
    wordIds: lettersWords.get(index + 1) ?? [],
  }));

  const sets = Object.entries(SETS).map(([id, set]) => ({
    id,
    title: set.title,
    wordIds: set.words.map((name) => {
      const wordId = translit(name);
      if (!words.has(wordId)) throw new Error(`комплект «${set.title}»: нет слова «${name}»`);
      return wordId;
    }),
  }));

  return {
    letters,
    syllables: [...syllables.values()],
    words: [...words.values()],
    sets,
  };
}
