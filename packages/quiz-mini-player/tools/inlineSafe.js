// packages/quiz-mini-player/tools/inlineSafe.js
//
// Код, вшиваемый в <script>…</script>, не должен содержать закрывающий тег
// script: парсер HTML закрыл бы блок на этом месте, не глядя на то, что это
// строка внутри JS. Обратная косая перед «/» для JavaScript ничего не меняет, а
// для парсера HTML это уже не тег.
//
// ОСТОРОЖНО С ЭКРАНИРОВАНИЕМ. В строке замены должна получиться НАСТОЯЩАЯ
// обратная косая, то есть в исходнике их две. С одной функция молча ничего не
// делает — так она и была написана в первый раз, и второй раз тоже: косую
// «съела» оболочка при записи файла. Поэтому у функции есть тест.
'use strict';

const BACKSLASH = String.fromCharCode(92);

function inlineSafe(code) {
  return String(code).replace(/<\/(script)/gi, '<' + BACKSLASH + '/$1');
}

module.exports = { inlineSafe };
